#include <unistd.h>

int	f_n2(char *n1, char *n2)
{
	char	new1[3];

	new1[0] = n1[0];
	new1[1] = n1[1];
	new1[2] = ' ';
	write(1, new1, 3);
	write(1, n2, 2);
	if (n1[0] == '9' && n1[1] == '8' && n2[0] == '9' && n2[1] == '9')
		return (1);
	else
	{
		write(1, ", ", 2);
		return (0);
	}
}

void	f_print_n2(char *n1)
{
	char	n2[2];

	n2[0] = n1[0];
	n2[1] = n1[1] + 1;
	while (n2[0] <= '9')
	{
		while (n2[1] <= '9')
		{
			if (f_n2(n1, n2))
				return ;
			n2[1]++;
		}
		n2[1] = '0';
		n2[0]++;
	}
}

void	ft_print_comb2(void)
{
	char	n1[2];

	n1[0] = '0';
	while (n1[0] <= '9')
	{
		n1[1] = '0';
		while (n1[1] <= '9')
		{
			f_print_n2(n1);
			n1[1]++;
		}
		n1[0]++;
	}
}
