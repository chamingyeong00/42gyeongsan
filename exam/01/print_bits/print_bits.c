#include <unistd.h>

void	print_bits(unsigned char octest)
{
	int	i;
	int	bit;

	i = 8;
	while(i > 0)
	{
		i--;
		bit = ((octest >> i) & 1) + '0';
		write(1, &bit, 1);
	}
}

int	main(void)
{
	print_bits(5);
}
