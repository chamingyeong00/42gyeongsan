#include <stdio.h>

int	is_power_of_2(unsigned int n)
{
	if (n == 0)
	{
		return (0);
	}
	else
	{
		if ((n & (-n)) == n)
			return (1);
		else
			return (0);
	}
}

int	main(void)
{
	printf("%d", is_power_of_2(8));
}
