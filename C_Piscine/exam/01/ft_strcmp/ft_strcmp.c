#include <stdio.h>

int	ft_strcmp(char *s1, char *s2)
{
	int	i;

	i = 0;
	while (s2[i] != '\0')
	{
		s1[i] = s2[i];
		i++;
	}
	s1[i] = '\0';
	return (i);
}

int	main(void)
{
	char	a[] = "**********";
	char	b[] = "12345";
	printf("%d", ft_strcmp(a, b));
}
