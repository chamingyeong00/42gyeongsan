#include "libft.h"

size_t	ft_strlen(const char *str)
{
	unsigned int	i;
	unsigned int	cnt;

	i = 0;
	cnt = 0;
	while (str[i] != '\0')
	{
		cnt++;
		i++;
	}
	return (cnt);
}
