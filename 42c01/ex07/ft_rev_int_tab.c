void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	s;
	int	temp;

	s = size - 1;
	i = 0;
	while (i < s)
	{
		temp = tab[i];
		tab[i] = tab[s];
		tab[s] = temp;
		i++;
		s--;
	}
}
