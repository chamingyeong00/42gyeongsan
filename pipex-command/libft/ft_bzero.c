#include "libft.h"

void	ft_bzero(void *dest, size_t n)
{
	unsigned char		*ptr;
	size_t				i;

	ptr = (unsigned char *) dest;
	i = 0;
	while (i < n)
	{
		ptr[i] = 0;
		i++;
	}
}
